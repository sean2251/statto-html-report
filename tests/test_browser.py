class PlainEditorTests(BrowserTestCase):
    """The Set up editor as generated by the command-line script, its data in
    the browser's localStorage."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        partial = os.path.join(cls.tmp.name, "partial.statto")
        with open(partial, "wb") as f:
            f.write(without_earliest_game(example_bytes()))
        for name, src in (("partial.html", partial), ("full.html", EXAMPLE)):
            with open(os.path.join(cls.tmp.name, name), "w", encoding="utf-8") as f:
                f.write(generate_html(src)[0])
        cls.server, cls.base = serve_directory(cls.tmp.name)

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()
        cls.tmp.cleanup()

    def write_page(self, name, html):
        with open(os.path.join(self.tmp.name, name), "w", encoding="utf-8") as f:
            f.write(html)
        return self.base + name

    def seed_legacy_data(self, page):
        """Data as an older editor saved it for the partial export, where
        Night Herons is game 0 and Tumbleweed game 1."""
        page.evaluate("""team => {
          localStorage.setItem('statto-report-setup::' + team, JSON.stringify({ version: 1,
            tournaments: [{ id: 't1', label: 'Spring', gameIndices: [1] }],
            videoLinks: { '0': 'https://youtu.be/NH', '1': 'https://youtu.be/TW' }, playerPhotos: {} }));
          localStorage.setItem('statto-report-lines::' + team, JSON.stringify({ version: 1,
            lines: [{ id: 'l1', name: 'O line', pointKeys: ['1|1', '1|2'] }], tournamentLabels: {} }));
        }""", TEAM)

    def test_saved_data_stays_with_its_games_when_an_earlier_game_is_added(self):
        page = self.new_page()
        page.goto(self.base + "partial.html")
        self.seed_legacy_data(page)
        page.reload()
        stored = page.evaluate("team => JSON.parse(localStorage.getItem('statto-report-setup::' + team))", TEAM)
        self.assertEqual(stored["version"], 2, "old data is converted when the editor opens")

        # The full export sorts Glass Cannons first, shifting the other two.
        page.goto(self.base + "full.html")
        self.assertEqual(self.setup_table(page), [
            ["Glass Cannons", "", "— Unassigned —"],
            ["Night Herons", "https://youtu.be/NH", "— Unassigned —"],
            ["Tumbleweed", "https://youtu.be/TW", "Spring"],
        ])
        lines = page.evaluate("() => loadLinesData().lines")
        self.assertEqual(lines[0]["pointKeys"], ["2|1", "2|2"], "line points follow Tumbleweed to its new position")

    def test_saving_from_a_partial_export_keeps_the_missing_games_links(self):
        page = self.new_page()
        page.goto(self.base + "full.html")
        self.set_video_link(page, 0, "https://youtu.be/GC")
        page.goto(self.base + "partial.html")
        self.set_video_link(page, 0, "https://youtu.be/NH2")  # a save from a build without Glass Cannons
        page.goto(self.base + "full.html")
        self.assertEqual([r[1] for r in self.setup_table(page)],
                         ["https://youtu.be/GC", "https://youtu.be/NH2", ""])

    def test_tagging_page_uses_its_own_video_link(self):
        page = self.new_page()
        page.goto(self.base + "full.html")
        self.set_video_link(page, 2, "https://youtu.be/TWreal")
        url = self.write_page("tag_tumbleweed.html", page.evaluate("() => gameTaggingPageHtml(2)"))

        helper = self.new_page()  # a helper's browser...
        helper.goto(self.base + "full.html")
        # ...that already has another page's stale setup saved for this team
        helper.evaluate("""team => localStorage.setItem('statto-report-setup::' + team,
            JSON.stringify({ version: 2, videoLinks: {}, tournaments: [], playerPhotos: {} }))""", TEAM)
        helper.goto(url)
        helper.wait_for_selector("#topnav .tab.active")
        self.assertEqual(helper.evaluate("() => loadSetupData().videoLinks[2]"), "https://youtu.be/TWreal")
        self.assertEqual(helper.title(), "vs Tumbleweed — %s tagging" % TEAM)

    def test_team_report_renders_every_tab(self):
        page = self.new_page()
        page.goto(self.base + "full.html")
        self.set_video_link(page, 1, "https://youtu.be/NHreal")
        url = self.write_page("team_report.html", page.evaluate("() => teamReportHtml()"))
        viewer_ctx = self.new_context()
        # A first-time viewer gets a guided tour of each tab; mark them all as
        # already seen so they don't cover the page.
        # (Guarded: this also runs on about:blank, which has no storage.)
        viewer_ctx.add_init_script("""try { localStorage.setItem('statto-report-tours-seen::' + %s, JSON.stringify(
            Object.fromEntries(['season', 'game', 'data-editor', 'player-analysis', 'line-analysis',
              'thrower-receiver-analysis', 'field-analysis', 'gender-analysis', 'time-series',
              'advanced-stats', 'raw-data'].map(k => [k, true])))); } catch (e) {}""" % json.dumps(TEAM))
        viewer = self.new_page(viewer_ctx)
        viewer.goto(url)
        tabs = viewer.query_selector_all("#topnav button.tab[data-target]")
        self.assertGreaterEqual(len(tabs), 8)
        for tab in tabs:
            if tab.is_visible():
                tab.click()
                self.assertFalse(viewer.is_visible(".tour-root"))
        self.assertEqual(viewer.evaluate("() => loadSetupData().videoLinks[1]"), "https://youtu.be/NHreal")
        self.assertIsNone(viewer.evaluate("() => APP"))



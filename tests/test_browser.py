class AppTests(BrowserTestCase):
    """The Statto Reports app: home page, the editor saving to disk, publishing,
    and sharing a game through the shared tagging site."""

    def setUp(self):
        super().setUp()
        self.tmp = tempfile.TemporaryDirectory()
        settings = Settings(os.path.join(self.tmp.name, "settings.json"))
        settings.values["seasonsDir"] = os.path.join(self.tmp.name, "seasons")
        self.app = App(settings)
        self.app.store.ensure_root()
        self.server = make_server(self.app, 0)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        self.base = "http://127.0.0.1:%d" % self.server.server_address[1]

    def tearDown(self):
        try:
            super().tearDown()
        finally:
            self.server.shutdown()
            self.server.server_close()
            self.tmp.cleanup()

    def season_dir(self, name):
        return os.path.join(self.tmp.name, "seasons", name)

    def disk(self, name):
        """The season's saved data on disk ({} before the first save)."""
        try:
            with open(os.path.join(self.season_dir(name), "season_data.json"), encoding="utf-8") as f:
                return json.load(f)
        except FileNotFoundError:
            return {}

    def wait_saved(self, page):
        page.wait_for_selector(".app-status-saved", timeout=10000)

    def make_season(self, name, statto_bytes, data):
        """Create a season through the API (the home page is tested separately)."""
        page = self.new_page()
        page.goto(self.base + "/")
        result = page.evaluate("""async (args) => {
          const r = await fetch('/api/seasons', { method: 'POST', headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(args) });
          return r.json();
        }""", {"name": name, "statto": base64.b64encode(statto_bytes).decode(), "data": data})
        return page, self.base + "/seasons/" + quote(result["id"], safe="") + "/editor"

    def test_season_workflow_from_home_page_to_published_report(self):
        tmpfile = lambda n: os.path.join(self.tmp.name, n)  # noqa: E731
        with open(tmpfile("partial.statto"), "wb") as f:
            f.write(without_earliest_game(example_bytes()))
        with open(tmpfile("old.json"), "w") as f:
            json.dump(legacy_bundle({"0": "https://youtu.be/NH", "1": "https://youtu.be/TW"},
                                    tournaments=[{"id": "t1", "label": "Spring", "gameIndices": [1]}]), f)

        # Create the season on the home page, bringing in an older editor's export.
        page = self.new_page()
        page.goto(self.base + "/")
        page.wait_for_selector("#empty:not([hidden])")
        page.fill("#c-name", "RAMP Test")
        page.set_input_files("#c-statto", tmpfile("partial.statto"))
        page.set_input_files("#c-data", tmpfile("old.json"))
        with page.expect_navigation(url="**/editor"):
            page.click("#c-go")
        self.wait_saved(page)
        disk = wait_until(lambda: self.disk("RAMP Test")["setup"].get("version") == 2 and self.disk("RAMP Test"),
                          message="converted data on disk")
        self.assertEqual(sorted(disk["setup"]["videoLinks"].values()), ["https://youtu.be/NH", "https://youtu.be/TW"])
        self.assertEqual(page.text_content("#topnav .brand"), "RAMP Test")

        # An edit autosaves to the season folder.
        self.set_video_link(page, 0, "https://youtu.be/NH2")
        wait_until(lambda: "https://youtu.be/NH2" in self.disk("RAMP Test")["setup"]["videoLinks"].values(),
                   message="autosave")

        # A newer export with an earlier-dated game.
        page.click("a.app-home-link")
        page.wait_for_selector(".card")
        page.set_input_files(".card input[type=file]", EXAMPLE)
        page.wait_for_selector("#flash:not([hidden])")
        self.assertIn("New: vs Glass Cannons", page.text_content("#flash"))
        page.click(".card a.btn.primary")
        self.assertEqual(self.setup_table(page), [
            ["Glass Cannons", "", "— Unassigned —"],
            ["Night Herons", "https://youtu.be/NH2", "— Unassigned —"],
            ["Tumbleweed", "https://youtu.be/TW", "Spring"],
        ])

        # Publish into the season's folder; the file carries no app data.
        page.click("text=Publish Team Report")
        page.wait_for_selector(".app-dialog")
        published = os.path.join(self.season_dir("RAMP Test"), "published")
        name = wait_until(lambda: os.listdir(published) if os.path.isdir(published) else None, message="published file")[0]
        with open(os.path.join(published, name), encoding="utf-8") as f:
            html = f.read()
        self.assertNotIn("window.__STATTO_APP__={", html)
        self.assertNotIn('"seasonId"', html)
        viewer = self.new_page()
        viewer.goto(self.base + "/seasons/RAMP%20Test/published/" + name)
        viewer.wait_for_selector("#topnav button.tab")
        self.assertEqual(viewer.evaluate("() => loadSetupData().videoLinks[1]"), "https://youtu.be/NH2")

    def test_share_a_game_through_the_shared_tagging_site_and_upload_the_tags(self):
        links = {"0": "https://youtu.be/GC", "1": "https://youtu.be/NH", "2": "https://youtu.be/TW"}
        _, editor_url = self.make_season("Share", example_bytes(), legacy_bundle(links))
        page = self.new_page()
        page.goto(editor_url)
        self.wait_saved(page)

        # Share for tagging -> game file + helper message.
        page.query_selector_all("button:has-text('Share for tagging')")[2].click()
        message = page.input_value(".app-dialog textarea")
        self.assertIn("vs Tumbleweed", message)
        self.assertIn("https://sean2251.github.io/statto-html-report/", message)
        with page.expect_download() as dl:
            page.click(".app-dialog button:has-text('Download game file')")
        game_file = os.path.join(self.tmp.name, dl.value.suggested_filename)
        dl.value.save_as(game_file)
        self.assertTrue(game_file.endswith(".tagging.json"))
        page.click(".app-dialog button:has-text('Done')")

        # A helper, in their own browser, opens the shared site (served here by the app).
        helper = self.new_page()
        helper.goto(self.base + "/tagging-site/")
        helper.set_input_files("#file", game_file)
        helper.wait_for_selector("#topnav .tab.active")
        self.assertEqual(helper.evaluate("() => loadSetupData().videoLinks[0]"), "https://youtu.be/TW")
        helper.evaluate("""() => { const a = loadAnnotations(); const p = REPORT.games[0].points[0].passes[0];
            a.passes[p.uuid] = { hand: 'Flick', timestamp: 12 }; saveAnnotations(a); }""")
        helper.reload()  # coming back later reopens the same game
        helper.wait_for_selector("#topnav .tab.active")
        self.assertEqual(helper.evaluate("() => REPORT.games[0].opponent"), "Tumbleweed")
        with helper.expect_download() as dl:
            helper.click("button:has-text('Export annotations JSON')")
        tags_file = os.path.join(self.tmp.name, dl.value.suggested_filename)
        dl.value.save_as(tags_file)
        helper.click("#topnav a:has-text('Games')")
        helper.wait_for_selector("#games li")
        self.assertIn("1 events tagged", helper.text_content("#games li"))

        # Back in the editor: Upload tags on Tumbleweed's row.
        page.query_selector_all("table.setup-games input[type=file]")[2].set_input_files(tags_file)
        wait_until(lambda: len(self.disk("Share")["annotations"]["passes"]) == 1, message="uploaded tags on disk")
        self.assertEqual(page.eval_on_selector_all(".setup-tag-count", "e => e.map(x => x.textContent)")[2][:2], "1/")

    def test_two_windows_editing_the_same_season(self):
        _, editor_url = self.make_season("Two", example_bytes(), None)
        ctx = self.new_context()
        first, second = self.new_page(ctx), self.new_page(ctx)
        first.goto(editor_url)
        second.goto(editor_url)
        self.setup_table(first)
        self.setup_table(second)

        self.set_video_link(second, 0, "https://youtu.be/SECOND")
        links = lambda: (self.disk("Two").get("setup") or {}).get("videoLinks", {}).values()  # noqa: E731
        wait_until(lambda: "https://youtu.be/SECOND" in links(), message="second window's save")
        self.set_video_link(first, 0, "https://youtu.be/FIRST")
        first.wait_for_selector(".app-status-conflict")
        self.assertNotIn("https://youtu.be/FIRST", links(), "a stale window must not silently overwrite")
        first.click("button:has-text('Keep this window')")
        wait_until(lambda: "https://youtu.be/FIRST" in links(), message="kept version saved")
        self.wait_saved(first)


# ---------- the shared tagging site on its own ----------

class TaggingSiteTests(BrowserTestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        with open(os.path.join(cls.tmp.name, "index.html"), "w", encoding="utf-8") as f:
            f.write(build_tagging_site_html())
        cls.server, cls.base = serve_directory(cls.tmp.name)

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()
        cls.tmp.cleanup()

    def game_file(self, mutate=None):
        """A game file made by the real editor code."""
        tmp = os.path.join(self.tmp.name, "editor.html")
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(generate_html(EXAMPLE)[0])
        page = self.new_page()
        page.goto(self.base + "editor.html")
        data = page.evaluate("() => buildTaggingGameFile(1)")
        if mutate:
            mutate(data)
        path = os.path.join(self.tmp.name, "game.tagging.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f)
        return path

    def test_rejects_a_file_that_isnt_a_game_file(self):
        bad = os.path.join(self.tmp.name, "bad.json")
        with open(bad, "w") as f:
            json.dump({"hello": "world"}, f)
        page = self.new_page()
        page.goto(self.base)
        page.set_input_files("#file", bad)
        page.wait_for_selector("#error:not([hidden])")
        self.assertIn("isn’t a Statto game file", page.text_content("#error"))

    def test_text_in_the_game_file_cant_break_the_page(self):
        evil = "</script><img src=x onerror=window.__pwned=1>"

        def mutate(data):
            data["title"] = evil
            data["report"]["games"][0]["opponent"] = evil
            data["setup"]["videoLinks"] = {data["gameUUID"]: "https://youtu.be/X" + evil}
        page = self.new_page()
        page.goto(self.base)
        page.set_input_files("#file", self.game_file(mutate))
        page.wait_for_selector("#topnav .tab.active")
        self.assertEqual(page.title(), evil)
        self.assertIsNone(page.evaluate("() => window.__pwned || null"))
        self.assertTrue(page.evaluate("() => loadSetupData().videoLinks[0]").endswith(evil))



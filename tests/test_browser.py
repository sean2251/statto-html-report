"""Browser tests: drive the real pages in headless Chromium with Playwright.

These cover what the unit tests can't -- the report's JavaScript: the Set up
editor, autosave in the app, the tagging pages and the shared tagging site.

They need Playwright, which isn't part of the standard library:

    pip install playwright
    python3 -m playwright install chromium

Without it these tests are skipped (so `python3 -m unittest discover -s tests`
still works anywhere). CI sets STATTO_REQUIRE_BROWSER_TESTS=1 so a missing
browser fails the run instead of silently skipping it.
"""


// Builds the team site's static files into public/ from:
//   web/                          the site's own pages (login, editor, hub, viewer, settings)
//   ../statto_report/templates/   the report page (report.html/css/js) and the stats engine (stats.js)
//
// public/ is committed, so a team deploying the site (e.g. with the "Deploy to
// Cloudflare" button, which copies only this folder) needs no build step.
// tests/test_site.py checks it's up to date: after changing anything above,
// run `node site/build.mjs` (or `npm run build` in site/) and commit public/.
//
//   node build.mjs [output directory]
import { mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const templates = join(here, '..', 'statto_report', 'templates');
const out = process.argv[2] || join(here, 'public');

const read = name => readFileSync(join(templates, name), 'utf8');

// The report page with its CSS and JS inlined, title and data left as
// placeholders (statto_report/render.py's page_template, in JavaScript).
const template = read('report.html')
  .replace('__REPORT_CSS__', () => read('report.css'))
  .replace('__REPORT_JS__', () => read('report.js'));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'assets'), { recursive: true });
writeFileSync(join(out, 'assets', 'report-template.js'),
  '// Generated by site/build.mjs from statto_report/templates -- do not edit.\n' +
  'window.STATTO_REPORT_TEMPLATE = ' + JSON.stringify(template).replace(/</g, '\\u003c') + ';\n');
copyFileSync(join(templates, 'stats.js'), join(out, 'assets', 'stats.js'));
for (const name of readdirSync(join(here, 'web'))) copyFileSync(join(here, 'web', name), join(out, name));
console.log('Built the team site into ' + out);

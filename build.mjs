// Builds the site's static files into public/ from:
//   web/      the site's own pages (sign-in, home, Season setup, tagging hub,
//             Team Report, settings, Upload new team)
//   report/   the report page (report.html/css/js) and the stats engine (stats.js)
//
// public/ is committed, so deploying (Cloudflare's Git integration, or the
// "Deploy to Cloudflare" button) needs no build step. tests/test_stats.py
// checks it's up to date: after changing web/ or report/, run `npm run build`
// and commit public/.
//
//   node build.mjs [output directory]
import { mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const report = join(here, 'report');
const out = process.argv[2] || join(here, 'public');

const read = name => readFileSync(join(report, name), 'utf8');

// The report page with its CSS and JS inlined; the title and the report data
// are filled in by the page that shows it (web/site.js writeReportPage).
const template = read('report.html')
  .replace('__REPORT_CSS__', () => read('report.css'))
  .replace('__REPORT_JS__', () => read('report.js'));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'assets'), { recursive: true });
writeFileSync(join(out, 'assets', 'report-template.js'),
  '// Generated by build.mjs from report/ -- do not edit.\n' +
  'window.STATTO_REPORT_TEMPLATE = ' + JSON.stringify(template).replace(/</g, '\\u003c') + ';\n');
copyFileSync(join(report, 'stats.js'), join(out, 'assets', 'stats.js'));
for (const name of readdirSync(join(here, 'web'))) copyFileSync(join(here, 'web', name), join(out, name));
console.log('Built the site into ' + out);
